function location(/** @type {*} */ event) {
  return (
    escapeHumanText(event.path ?? "<stdin>") +
    (event.line === undefined ? "" : ":" + escapeHumanText(event.line, 24)) +
    (event.column === undefined
      ? ""
      : ":" + escapeHumanText(event.column, 24)) +
    (event.record === undefined
      ? ""
      : " [record " + escapeHumanText(event.record, 24) + "]")
  );
}

function failureAdvice(/** @type {*} */ event) {
  const text =
    String(event.code ?? "") + " " + String(event.message ?? "").slice(0, 2048);
  if (/capacity|quota|maximum|byte-limit/u.test(text))
    return "Reduce the selected input or explicitly review the applicable resource control; integrity checks remain required.";
  if (/stale|changed|freshness/u.test(text))
    return "Rerun against fresh source and policy observations; do not reuse this preview.";
  if (/protected|ownership|producer|permission|rewrites-disabled/u.test(text))
    return "Update the owning source or regenerate through its producer; this command cannot grant rewrite authority.";
  return "Correct the reported cause and rerun; this operation did not establish successful completion.";
}

function context(/** @type {*} */ event) {
  const scope = event.operationScope;
  const description =
    scope?.kind === "selected-files"
      ? "Selected-file check"
      : scope?.kind === "stdin"
        ? "Stdin operation"
        : scope?.kind === "immutable-git-json"
          ? "Immutable-Git JSON qualification"
          : "Repository operation";
  const origin = event.configurationOrigin;
  return (
    description +
    (event.root === undefined ? "" : "; root " + escapeHumanText(event.root)) +
    (scope?.policy === "explicit-contract"
      ? "; policy explicit contract"
      : origin?.kind === "repository-absence" || origin?.kind === "git-absence"
        ? "; policy packaged defaults (configuration absence observed)"
        : origin?.path
          ? "; policy " + escapeHumanText(origin.path)
          : "") +
    ".\n"
  );
}

/** Render one bounded human event without I/O or changes to machine evidence.
 * @param {*} event
 * @param {{quiet?: boolean, level?: 'info'|'warning'|'error'}} [options]
 */
export function renderHumanEvent(
  event,
  { quiet = false, level = "info" } = {},
) {
  if (event.type === "finding") {
    const identifier =
      String(event.ruleId ?? event.phase ?? "unknown") +
      "/" +
      String(event.messageId ?? "unknown");
    const message =
      messages[identifier] ??
      "A source requirement failed. Review this location and the named rule or phase before retrying.";
    return (
      location(event) +
      ": " +
      message +
      " (" +
      escapeHumanText(identifier, 256) +
      ")\n"
    );
  }
  if (event.type === "nfc-key-collision-risk")
    return level === "error"
      ? ""
      : location(event) +
          ": NFC normalization could make this key equal to another key at " +
          escapeHumanText(event.priorLine, 24) +
          ":" +
          escapeHumanText(event.priorColumn, 24) +
          ". Decoded keys remain preserved; reconcile the owning keys before normalizing. (json-quality/nfc-strings/collision-risk)\n";
  if (event.type === "failure")
    return (
      escapeHumanText(event.code, 128) +
      ": " +
      escapeHumanText(event.message, String(event.message ?? "").length) +
      " " +
      failureAdvice(event) +
      "\n"
    );
  if (event.type === "write-failure")
    return (
      "Incomplete replacement; confirmed writes " +
      escapeHumanText(event.writtenPathCount, 24) +
      (event.uncertainPath
        ? "; uncertain path " + escapeHumanText(event.uncertainPath)
        : "") +
      ": " +
      escapeHumanText(event.message, String(event.message ?? "").length) +
      ". Inspect confirmed writes and any uncertain path, then rerun fresh preflight.\n"
    );
  if (event.type === "selection-terminal") {
    const failed =
      event.complete === false || event.contractSatisfied === false;
    if (quiet && !failed) return "";
    return (
      "Selected files " +
      (event.complete === false ? "incomplete" : "checked") +
      ": " +
      escapeHumanText(
        event.completedSourceCount ??
          event.selectedSourceCount ??
          event.selectedPathCount,
        24,
      ) +
      "; contract " +
      (event.contractSatisfied ? "satisfied" : "failed") +
      "; repository-wide obligations were not assessed.\n"
    );
  }
  if (
    event.type === "format-preview-terminal" ||
    event.type === "normalization-preview-terminal"
  ) {
    const complete = event.complete && event.preflightComplete;
    if (quiet && complete) return "";
    return (
      (event.type === "format-preview-terminal"
        ? "Formatting"
        : "Normalization") +
      " preview " +
      (complete ? "complete" : event.complete ? "refused" : "incomplete") +
      (event.changedPathCount === undefined
        ? ""
        : "; changed " +
          escapeHumanText(event.changedPathCount, 24) +
          "/" +
          escapeHumanText(event.selectedPathCount, 24)) +
      (event.findingCount === undefined
        ? ""
        : "; remaining findings " + escapeHumanText(event.findingCount, 24)) +
      (event.message === undefined
        ? ""
        : "; " +
          escapeHumanText(event.message, String(event.message ?? "").length)) +
      ". No source files were replaced. Run check for the full repository verdict.\n"
    );
  }
  if (event.type === "execution-terminal" || event.type === "terminal") {
    if (quiet && event.contractSatisfied) return "";
    const scope = event.operationScope;
    const label =
      scope?.kind === "immutable-git-json"
        ? "Immutable-Git JSON contract"
        : event.type === "terminal" || scope?.kind === "stdin"
          ? "Raw source contract"
          : "Complete repository contract";
    return (
      label +
      " " +
      (event.contractSatisfied ? "satisfied" : "failed") +
      "; shared quality " +
      (event.qualityPassed ? "passed" : "has findings") +
      (scope?.kind === "immutable-git-json" || event.type === "terminal"
        ? "; repository-wide obligations were not assessed"
        : "") +
      ".\n"
    );
  }
  if (quiet) return "";
  if (
    event.type === "execution" ||
    event.type === "selection" ||
    event.type === "operation"
  )
    return context(event);
  if (event.type === "written")
    return "Written " + escapeHumanText(event.path) + "\n";
  if (event.type === "write-terminal")
    return (
      "Replacement complete; written " +
      escapeHumanText(event.writtenPathCount, 24) +
      "; remaining quality findings " +
      escapeHumanText(event.findingCount, 24) +
      ". Run check for the full repository verdict.\n"
    );
  if (event.type === "format-preview-change")
    return (
      escapeHumanText(event.path) +
      ": " +
      (event.changed ? "would change" : "unchanged") +
      "; bytes " +
      escapeHumanText(event.sourceByteLength, 24) +
      " -> " +
      escapeHumanText(event.candidateByteLength, 24) +
      "; SHA-256 " +
      escapeHumanText(event.sourceSha256, 64) +
      " -> " +
      escapeHumanText(event.candidateSha256, 64) +
      "\n"
    );
  if (event.type === "normalization-preview-change")
    return (
      escapeHumanText(event.path) +
      ": NFC change at byte " +
      escapeHumanText(event.sourceByteOffset, 24) +
      "; pointer " +
      escapeHumanText(event.pointer, 256) +
      "; decoded SHA-256 " +
      escapeHumanText(event.decodedSha256, 64) +
      " -> " +
      escapeHumanText(event.normalizedSha256, 64) +
      "\n"
    );
  return "";
}
