import assert from "node:assert/strict";
import test from "node:test";
import { escapeHumanText, renderHumanEvent } from "../src/cli-messages.js";

const finding = {
  type: "finding",
  severity: "error",
  phase: "lint",
  path: "authored.json",
  line: "3",
  column: "8",
  ruleId: "json-quality/nfc-strings",
  messageId: "unnormalized",
};

test("human messages explain concrete native findings and safe repair choices", () => {
  assert.equal(
    renderHumanEvent(finding),
    "authored.json:3:8: String is not NFC-normalized. Preview with normalize --dry-run; formatting preserves this value. (json-quality/nfc-strings/unnormalized)\n",
  );
  for (const [ruleId, messageId, phase, expected] of [
    [
      "json-quality/nfc-strings",
      "collision",
      "lint",
      /Reconcile them in the owning source before normalizing/u,
    ],
    [
      "json-quality/nfc-strings",
      "preservationMismatch",
      "lint",
      /preservation contract.*owning value/u,
    ],
    [
      "json/no-duplicate-keys",
      "duplicateKey",
      "lint",
      /repeats a decoded key.*Reconcile duplicate members/u,
    ],
    [
      "json-quality/no-empty-keys",
      "emptyKey",
      "lint",
      /empty or contains only whitespace/u,
    ],
    [
      "json/no-unsafe-values",
      "unsafeNumber",
      "lint",
      /cannot be represented safely/u,
    ],
    [null, "invalid-utf8-or-bom", "bytes", /Save UTF-8 without a BOM/u],
    [null, "syntax", "syntax", /Correct the syntax.*before formatting/u],
    [
      null,
      "format-contract",
      "presentation",
      /format --dry-run.*regenerated by their owner/u,
    ],
    [
      null,
      "expected-bytes-or-diagnostics-mismatch",
      "expectation",
      /owning expectation together/u,
    ],
  ])
    assert.match(
      renderHumanEvent({ ...finding, ruleId, messageId, phase }),
      expected,
    );
});

test("quiet and diagnostic filtering cannot suppress findings or operational failures", () => {
  const failed = {
      type: "failure",
      code: "capacity-exhausted",
      message: "source-byte-capacity",
    },
    partial = {
      type: "write-failure",
      writtenPathCount: "1",
      uncertainPath: "a.json",
      message: "interrupted",
    };
  for (const event of [finding, failed, partial]) {
    const before = structuredClone(event);
    assert.equal(
      renderHumanEvent(event, { quiet: true, level: "error" }),
      renderHumanEvent(event),
    );
    assert.deepEqual(event, before);
  }
  assert.match(
    renderHumanEvent(failed),
    /explicitly review.*resource control/u,
  );
  assert.match(
    renderHumanEvent(partial),
    /confirmed writes 1; uncertain path a.json.*Inspect confirmed writes/u,
  );
  assert.match(
    renderHumanEvent({
      type: "failure",
      code: "source-stale",
      message: "observations changed",
    }),
    /Rerun against fresh source and policy observations/u,
  );
  assert.match(
    renderHumanEvent({
      type: "failure",
      code: "protected-path",
      message: "producer-owned",
    }),
    /regenerate through its producer/u,
  );
});

test("quiet hides routine success while warning filtering remains presentation only", () => {
  const warning = {
    type: "nfc-key-collision-risk",
    path: "a.json",
    line: "1",
    column: "2",
    priorLine: "1",
    priorColumn: "1",
  };
  assert.match(
    renderHumanEvent(warning, { quiet: true, level: "warning" }),
    /Decoded keys remain preserved/u,
  );
  assert.equal(renderHumanEvent(warning, { level: "error" }), "");
  for (const event of [
    { type: "written", path: "a.json" },
    { type: "write-terminal", writtenPathCount: "1", findingCount: "2" },
    {
      type: "selection-terminal",
      complete: true,
      contractSatisfied: true,
      completedSourceCount: "2",
    },
    {
      type: "format-preview-terminal",
      complete: true,
      preflightComplete: true,
      selectedPathCount: "1",
      changedPathCount: "1",
    },
  ])
    assert.equal(renderHumanEvent(event, { quiet: true }), "");
  assert.match(
    renderHumanEvent(
      { type: "selection-terminal", complete: false, contractSatisfied: false },
      { quiet: true },
    ),
    /incomplete/u,
  );
  assert.match(
    renderHumanEvent(
      {
        type: "format-preview-terminal",
        complete: true,
        preflightComplete: false,
      },
      { quiet: true },
    ),
    /refused/u,
  );
});

test("bounded terminal escaping does not inspect event arguments or source values", () => {
  assert.equal(
    escapeHumanText("a\u001b[31m\r\n\u009b\u202e"),
    "a\\u001b[31m\\u000d\\u000a\\u009b\\u202e",
  );
  assert.equal(escapeHumanText("a".repeat(10000), 10), "aaaaaaaaaa…");
  const event = {
    ...finding,
    path: "evil\u001b[2J.json",
    messageId: "future\nidentifier",
  };
  Object.defineProperty(event, "arguments", {
    get() {
      throw new Error("arguments must stay unread");
    },
  });
  Object.defineProperty(event, "value", {
    get() {
      throw new Error("value must stay unread");
    },
  });
  const text = renderHumanEvent(event);
  assert.match(text, /evil\\u001b\[2J.json/u);
  assert.match(text, /named rule or phase/u);
  assert.match(text, /future\\u000aidentifier/u);
  assert.doesNotMatch(text.slice(0, -1), /\p{Cc}/u);
  // Full failure text is admitted by the report owner, not an implicit renderer
  // ceiling. The CLI process tests retain actual finite output refusal coverage.
  const message = "x".repeat(100000);
  assert.ok(
    renderHumanEvent({
      type: "failure",
      code: "failed",
      message,
    }).includes(message),
  );
});

test("scope and result messages keep repository acceptance distinct from selected checks and writes", () => {
  const selected = renderHumanEvent({
    type: "selection-terminal",
    complete: true,
    contractSatisfied: true,
    completedSourceCount: "2",
  });
  assert.equal(
    selected,
    "Selected files checked: 2; contract satisfied; repository-wide obligations were not assessed.\n",
  );
  assert.equal(
    renderHumanEvent({
      type: "execution-terminal",
      contractSatisfied: true,
      qualityPassed: true,
    }),
    "Complete repository contract satisfied; shared quality passed.\n",
  );
  assert.match(
    renderHumanEvent({
      type: "terminal",
      contractSatisfied: true,
      qualityPassed: true,
    }),
    /Raw source contract satisfied.*repository-wide obligations were not assessed/u,
  );
  assert.match(
    renderHumanEvent({
      type: "execution-terminal",
      contractSatisfied: true,
      qualityPassed: true,
      operationScope: { kind: "immutable-git-json" },
    }),
    /Immutable-Git JSON contract satisfied.*repository-wide obligations were not assessed/u,
  );
  assert.equal(
    renderHumanEvent({
      type: "write-terminal",
      writtenPathCount: "1",
      findingCount: "1",
    }),
    "Replacement complete; written 1; remaining quality findings 1. Run check for the full repository verdict.\n",
  );
  assert.match(
    renderHumanEvent({
      type: "selection",
      root: "C:/project",
      configurationOrigin: {
        kind: "repository-absence",
        path: ".json-quality.json",
      },
      operationScope: { kind: "selected-files", policy: "repository" },
    }),
    /Selected-file check; root C:\/project; policy packaged defaults \(configuration absence observed\)/u,
  );
  assert.match(
    renderHumanEvent({
      type: "operation",
      operationScope: { kind: "stdin", policy: "explicit-contract" },
    }),
    /Stdin operation; policy explicit contract/u,
  );
});

test("previews show candidate observations and remaining quality without claiming replacement", () => {
  const format = renderHumanEvent({
    type: "format-preview-change",
    path: "a.json",
    changed: true,
    sourceByteLength: "2",
    candidateByteLength: "3",
    sourceSha256: "a".repeat(64),
    candidateSha256: "b".repeat(64),
  });
  assert.match(
    format,
    /a.json: would change; bytes 2 -> 3; SHA-256 a{64} -> b{64}/u,
  );
  const terminal = renderHumanEvent({
    type: "format-preview-terminal",
    complete: true,
    preflightComplete: true,
    changedPathCount: "1",
    selectedPathCount: "2",
    findingCount: "3",
  });
  assert.match(
    terminal,
    /Formatting preview complete; changed 1\/2; remaining findings 3. No source files were replaced/u,
  );
  const normalization = renderHumanEvent({
    type: "normalization-preview-change",
    path: "a.json",
    sourceByteOffset: "12",
    pointer: "/key",
    decodedSha256: "a".repeat(64),
    normalizedSha256: "b".repeat(64),
  });
  assert.match(
    normalization,
    /NFC change at byte 12; pointer \/key; decoded SHA-256/u,
  );
});
